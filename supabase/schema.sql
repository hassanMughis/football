create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name text not null,
  rating integer not null default 75 check (rating between 50 and 99),
  available boolean not null default true,
  team integer not null default 0 check (team between 0 and 2),
  image_url text,
  sort_order integer not null default 0
);

create table if not exists public.squad_settings (
  id integer primary key,
  team_1_name text not null default 'Team 1',
  team_2_name text not null default 'Team 2'
);

insert into public.squad_settings (id, team_1_name, team_2_name)
values (1, 'Team 1', 'Team 2')
on conflict (id) do nothing;

alter table public.players enable row level security;
alter table public.squad_settings enable row level security;

drop policy if exists "public players read" on public.players;
drop policy if exists "public players write" on public.players;
drop policy if exists "public settings read" on public.squad_settings;
drop policy if exists "public settings write" on public.squad_settings;

create policy "public players read" on public.players for select to anon using (true);
create policy "public players write" on public.players for all to anon using (true) with check (true);
create policy "public settings read" on public.squad_settings for select to anon using (true);
create policy "public settings write" on public.squad_settings for all to anon using (true) with check (true);

