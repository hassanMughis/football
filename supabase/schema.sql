-- Save the whole shared squad in one transaction. A failed insert rolls back
-- the delete, so connection or validation errors cannot erase the old squad.
create or replace function public.save_team_maker_squad(
  p_players jsonb, p_team1_name text, p_team2_name text
) returns void language plpgsql security invoker set search_path = public as $$
declare
  item jsonb;
  position integer := 0;
begin
  if jsonb_typeof(p_players) is distinct from 'array' then
    raise exception 'Players must be an array';
  end if;
  if jsonb_array_length(p_players) > 100 then
    raise exception 'A squad supports at most 100 players';
  end if;
  if length(trim(p_team1_name)) not between 1 and 40 or
     length(trim(p_team2_name)) not between 1 and 40 then
    raise exception 'Team names must be between 1 and 40 characters';
  end if;
  -- Serialize saves to the shared squad.
  perform pg_advisory_xact_lock(7312904);
  delete from public.players;
  for item in select value from jsonb_array_elements(p_players) loop
    if length(trim(item->>'name')) not between 1 and 60 then
      raise exception 'Player names must be between 1 and 60 characters';
    end if;
    insert into public.players (name, rating, available, team, image_url, sort_order)
    values (trim(item->>'name'), (item->>'rating')::integer,
      (item->>'available')::boolean,
      case when (item->>'available')::boolean then (item->>'team')::integer else 0 end,
      nullif(item->>'imageUrl', ''), position);
    position := position + 1;
  end loop;
  insert into public.squad_settings (id, team_1_name, team_2_name)
  values (1, trim(p_team1_name), trim(p_team2_name))
  on conflict (id) do update set team_1_name = excluded.team_1_name,
    team_2_name = excluded.team_2_name;
end;
$$;
revoke execute on function public.save_team_maker_squad(jsonb, text, text) from public;
grant execute on function public.save_team_maker_squad(jsonb, text, text) to anon;
