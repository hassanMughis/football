-- Run this once in the Supabase SQL Editor after rich-player-migration.sql.
-- Football players stay in public.players. Cricket players use their own table
-- because their roles, profiles and card attributes are different.

begin;

alter table public.squad_settings
  add column if not exists sport_mode text not null default 'football';

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'squad_settings_sport_mode_check'
      and conrelid = 'public.squad_settings'::regclass
  ) then
    alter table public.squad_settings
      add constraint squad_settings_sport_mode_check
      check (sport_mode in ('football', 'cricket'));
  end if;
end $$;

create or replace function public.sync_squad_sheet_sport_mode()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.sport_mode := case
    when new.app_state->>'sportMode' = 'cricket' then 'cricket'
    else 'football'
  end;
  return new;
end;
$$;

drop trigger if exists squad_settings_sync_sport_mode on public.squad_settings;
create trigger squad_settings_sync_sport_mode
before insert or update of app_state on public.squad_settings
for each row execute function public.sync_squad_sheet_sport_mode();

update public.squad_settings
set sport_mode = case
  when app_state->>'sportMode' = 'cricket' then 'cricket'
  else 'football'
end
where id = 1;

create table if not exists public.cricket_players (
  id bigint generated by default as identity primary key,
  client_id text not null unique,
  name text not null,
  rating numeric(3,1) not null default 0,
  custom_overall integer,
  overall integer,
  role text not null default 'All-rounder',
  batting_order integer not null default 6,
  batting_hand text not null default 'Right hand',
  bowling_style text not null default 'Right-arm medium',
  image_url text,
  flag text not null default 'PK',
  card_style text not null default 'electric',
  active boolean not null default true,
  batting integer,
  bowling integer,
  fielding integer,
  speed integer,
  power integer,
  technique integer,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint cricket_players_name_check check (char_length(btrim(name)) between 1 and 60),
  constraint cricket_players_rating_check check (rating between 0 and 10 and rating * 2 = trunc(rating * 2)),
  constraint cricket_players_custom_overall_check check (custom_overall is null or custom_overall between 1 and 99),
  constraint cricket_players_overall_check check (overall is null or overall between 1 and 99),
  constraint cricket_players_role_check check (role in ('Batter', 'Bowler', 'All-rounder', 'Wicketkeeper')),
  constraint cricket_players_batting_order_check check (batting_order between 1 and 11),
  constraint cricket_players_batting_hand_check check (batting_hand in ('Right hand', 'Left hand')),
  constraint cricket_players_card_style_check check (card_style in ('electric', 'classic', 'eclipse', 'crimson')),
  constraint cricket_players_batting_check check (batting is null or batting between 1 and 99),
  constraint cricket_players_bowling_check check (bowling is null or bowling between 1 and 99),
  constraint cricket_players_fielding_check check (fielding is null or fielding between 1 and 99),
  constraint cricket_players_speed_check check (speed is null or speed between 1 and 99),
  constraint cricket_players_power_check check (power is null or power between 1 and 99),
  constraint cricket_players_technique_check check (technique is null or technique between 1 and 99)
);

alter table public.cricket_players
