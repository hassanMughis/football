create or replace function public.save_cricket_players(p_players jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  player_id text;
  incoming_ids text[] := array[]::text[];
begin
  if jsonb_typeof(p_players) is distinct from 'array' then
    raise exception 'Cricket players must be a JSON array';
  end if;
  if jsonb_array_length(p_players) > 100 then
    raise exception 'A cricket squad supports at most 100 players';
  end if;

  for item in select value from jsonb_array_elements(p_players) loop
    player_id := btrim(item->>'id');
    if player_id is null or player_id = '' or char_length(player_id) > 80 then
      raise exception 'Every cricket player needs a valid ID';
    end if;
    if player_id = any(incoming_ids) then
      raise exception 'Cricket player IDs must be unique';
    end if;
    incoming_ids := array_append(incoming_ids, player_id);

    insert into public.cricket_players (
      client_id, name, rating, custom_overall, overall, role, batting_order, batting_hand,
      bowling_style, image_url, flag, card_style, active, batting, bowling,
      fielding, speed, power, technique, sort_order
    ) values (
      player_id,
      btrim(item->>'name'),
      coalesce((item->>'rating')::numeric, 0),
      nullif(item->>'customOverall', '')::integer,
      nullif(item->>'overall', '')::integer,
      coalesce(nullif(item->>'role', ''), 'All-rounder'),
      greatest(1, least(11, coalesce((item->>'battingOrder')::integer, 6))),
      coalesce(nullif(item->>'batting', ''), 'Right hand'),
      coalesce(nullif(item->>'bowling', ''), 'Right-arm medium'),
      nullif(item->>'image', ''),
      coalesce(nullif(item->>'flag', ''), 'PK'),
      case item->>'cardStyle'
        when 'classic' then 'classic'
        when 'royal' then 'classic'
        when 'eclipse' then 'eclipse'
        when 'prism' then 'eclipse'
        when 'crimson' then 'crimson'
        when 'inferno' then 'crimson'
        when 'electric' then 'electric'
        when 'aurora' then 'electric'
        else 'electric'
      end,
      coalesce((item->>'active')::boolean, true),
      nullif(item #>> '{stats,BAT}', '')::integer,
      nullif(item #>> '{stats,BWL}', '')::integer,
      nullif(item #>> '{stats,FLD}', '')::integer,
      nullif(item #>> '{stats,SPD}', '')::integer,
      nullif(item #>> '{stats,PWR}', '')::integer,
      nullif(item #>> '{stats,TEC}', '')::integer,
      coalesce((item->>'sortOrder')::integer, 0)
    )
    on conflict (client_id) do update set
      name = excluded.name,
      rating = excluded.rating,
      custom_overall = excluded.custom_overall,
      overall = excluded.overall,
      role = excluded.role,
      batting_order = excluded.batting_order,
      batting_hand = excluded.batting_hand,
      bowling_style = excluded.bowling_style,
      image_url = excluded.image_url,
      flag = excluded.flag,
      card_style = excluded.card_style,
      active = excluded.active,
      batting = excluded.batting,
      bowling = excluded.bowling,
      fielding = excluded.fielding,
      speed = excluded.speed,
      power = excluded.power,
      technique = excluded.technique,
      sort_order = excluded.sort_order;
  end loop;

  delete from public.cricket_players
  where not (client_id = any(incoming_ids));
end;
$$;

revoke all on function public.save_cricket_players(jsonb) from public;
grant execute on function public.save_cricket_players(jsonb) to anon, authenticated;

-- Preserve cricket players created before this dedicated table existed.
do $$
declare
  legacy_players jsonb;
begin
  select app_state #> '{cricket,players}' into legacy_players
  from public.squad_settings
  where id = 1;

  if not exists (select 1 from public.cricket_players)
    and jsonb_typeof(legacy_players) = 'array'
    and jsonb_array_length(legacy_players) > 0 then
    perform public.save_cricket_players(legacy_players);
  end if;
end $$;

-- Sport switches, teams, scores and commentary still arrive through the single
-- squad_settings row. Direct cricket-roster changes are also published.
do $$
begin
  if exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) and not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'squad_settings'
  ) then
    execute 'alter publication supabase_realtime add table public.squad_settings';
  end if;
  if exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) and not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'cricket_players'
  ) then
    execute 'alter publication supabase_realtime add table public.cricket_players';
  end if;
end $$;

commit;
